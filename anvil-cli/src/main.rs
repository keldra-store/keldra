    #[test]
    fn put_flags_select_exactly_one_typed_operation() {
        assert!(matches!(
            put_operation(false, None, false).unwrap(),
            Operation::Put(_)
        ));
        assert!(matches!(
            put_operation(true, None, false).unwrap(),
            Operation::PutIfAbsent(_)
        ));
        assert!(
            matches!(put_operation(false, Some(8), false).unwrap(), Operation::PutIfVersion(request) if request.expected_version == 8)
        );
        assert!(matches!(
            put_operation(false, None, true).unwrap(),
            Operation::PutImmutable(_)
        ));
        assert!(put_operation(true, Some(8), false).is_err());
        assert!(put_operation(true, None, true).is_err());
    }

