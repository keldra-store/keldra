    #[cfg(unix)]
    #[test]
    fn credential_file_loader_requires_stable_regular_mode_0600_bounded_file() {
        let directory = tempfile::tempdir().unwrap();
        let credential = directory.path().join("credential.json");
        std::fs::write(&credential, b"{}").unwrap();
        std::fs::set_permissions(&credential, std::fs::Permissions::from_mode(0o600)).unwrap();
        assert_eq!(load_credential_file(&credential).unwrap(), b"{}");

        std::fs::set_permissions(&credential, std::fs::Permissions::from_mode(0o644)).unwrap();
        assert!(load_credential_file(&credential).is_err());
        std::fs::set_permissions(&credential, std::fs::Permissions::from_mode(0o600)).unwrap();

        let link = directory.path().join("credential-link.json");
        symlink(&credential, &link).unwrap();
        assert!(load_credential_file(&link).is_err());

        let oversized = directory.path().join("oversized.json");
        std::fs::write(
            &oversized,
            vec![0_u8; super::MAX_CREDENTIAL_FILE_BYTES as usize + 1],
        )
        .unwrap();
        std::fs::set_permissions(&oversized, std::fs::Permissions::from_mode(0o600)).unwrap();
        assert!(load_credential_file(&oversized).is_err());
    }

